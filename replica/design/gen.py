#!/usr/bin/env python3
"""Generate platform tokens from tokens.json. Standard library only.

    python gen.py   # writes tokens.css, android/.../design/DesignTokens.kt, inlines preview.html

Run after every change to tokens.json (including the rebrand), then run
contrast.py. Never edit the generated files by hand.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
T = json.load(open(os.path.join(HERE, "tokens.json"), encoding="utf-8"))


def camel(name):
    parts = name.replace("_", "-").split("-")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def pascal(name):
    c = camel(name)
    return c[:1].upper() + c[1:]


def css():
    c = T["color"]
    out = ["/* Generated by gen.py from tokens.json. Do not edit. */", ":root {"]
    for k, v in c["light"].items():
        out.append("  --color-%s: %s;" % (k, v))
    for k, v in c["overlay"].items():
        out.append("  --overlay-%s: %s;" % (k, v))
    for k, v in T["type"].items():
        out.append("  --type-%s: %dpx/%dpx;" % (k, v["size"], v["line"]))
        out.append("  --weight-%s: %d;" % (k, v["weight"]))
    for i, v in enumerate(T["space"]):
        out.append("  --space-%d: %dpx;" % (i, v))
    for k, v in T["radius"].items():
        out.append("  --radius-%s: %dpx;" % (k, v))
    for k, v in T["size"].items():
        out.append("  --size-%s: %dpx;" % (k, v))
    for k in ("fast", "base", "slow", "ease"):
        out.append("  --motion-%s: %s;" % (k, T["motion"][k]))
    out.append("}")
    dark = ["  --color-%s: %s;" % (k, v) for k, v in c["dark"].items()]
    out += ['[data-theme="dark"] {'] + dark + ["}"]
    out += ["@media (prefers-color-scheme: dark) {",
            '  :root:not([data-theme="light"]) {'] + ["  " + d for d in dark] + ["  }", "}"]
    out += ["@media (prefers-reduced-motion: reduce) {",
            "  :root { --motion-fast: 0ms; --motion-base: 0ms; --motion-slow: 0ms; }", "}"]
    return "\n".join(out) + "\n"


def argb(hexv):
    return "Color(0xFF%s)" % hexv.lstrip("#").upper()


def kotlin():
    c = T["color"]
    L = ["// Generated by replica/design/gen.py from tokens.json. Do not edit.",
         "package app.tidemark.design",
         "",
         "import androidx.compose.runtime.Immutable",
         "import androidx.compose.runtime.staticCompositionLocalOf",
         "import androidx.compose.ui.graphics.Color",
         "import androidx.compose.ui.text.TextStyle",
         "import androidx.compose.ui.text.font.FontWeight",
         "import androidx.compose.ui.unit.dp",
         "import androidx.compose.ui.unit.sp",
         "",
         "@Immutable",
         "data class AppColors("]
    keys = list(c["light"].keys())
    L += ["    val %s: Color," % camel(k) for k in keys]
    L += ["    val isDark: Boolean,", ")", ""]
    for theme in ("light", "dark"):
        L.append("val %sAppColors = AppColors(" % theme.capitalize())
        L += ["    %s = %s," % (camel(k), argb(c[theme][k])) for k in keys]
        L += ["    isDark = %s," % ("true" if theme == "dark" else "false"), ")", ""]
    L.append("/** The floating counter sits on top of any video, so it has one fixed palette. */")
    L.append("object OverlayColors {")
    L += ["    val %s = %s" % (camel(k), argb(v)) for k, v in c["overlay"].items()]
    L += ["}", ""]
    L.append("object AppType {")
    for k, v in T["type"].items():
        line = "    val %s = TextStyle(fontFamily = AppFonts.Inter, fontSize = %d.sp, lineHeight = %d.sp, fontWeight = FontWeight(%d)" % (
            camel(k), v["size"], v["line"], v["weight"])
        if v.get("numeric"):
            line += ', fontFeatureSettings = "tnum"'
        if v.get("tracking"):
            line += ", letterSpacing = %s.sp" % v["tracking"]
        L.append(line + ")")
    L += ["}", ""]
    L.append("object Space {")
    names = ["none", "xxs", "xs", "sm", "md", "lg", "xl", "xxl", "x3", "x4", "x5"]
    for n, v in zip(names, T["space"]):
        L.append("    val %s = %d.dp" % (n, v))
    L += ["}", "", "object Radius {"]
    L += ["    val %s = %d.dp" % (camel(k), v) for k, v in T["radius"].items()]
    L += ["}", "", "object Size {"]
    L += ["    val %s = %d.dp" % (camel(k), v) for k, v in T["size"].items()]
    L += ["}", "", "object Motion {",
          "    const val FAST_MS = %s" % T["motion"]["fast"].rstrip("ms"),
          "    const val BASE_MS = %s" % T["motion"]["base"].rstrip("ms"),
          "    const val SLOW_MS = %s" % T["motion"]["slow"].rstrip("ms"),
          "    const val OVERLAY_HIDE_DELAY_MS = 1500",
          "}", "",
          "val LocalAppColors = staticCompositionLocalOf { LightAppColors }", ""]
    return "\n".join(L)


with open(os.path.join(HERE, "tokens.css"), "w", encoding="utf-8") as f:
    f.write(css())
KT_DIR = os.path.join(HERE, "..", "..", "android", "app", "src", "main", "java", "app", "tidemark", "design")
os.makedirs(KT_DIR, exist_ok=True)
with open(os.path.join(KT_DIR, "DesignTokens.kt"), "w", encoding="utf-8") as f:
    f.write(kotlin())

# Inline the CSS into preview.html so it renders as a single self-contained file.
pv = os.path.join(HERE, "preview.html")
if os.path.exists(pv):
    import re
    html = open(pv, encoding="utf-8").read()
    html = re.sub(r"/\* TOKENS:BEGIN.*?\*/.*?/\* TOKENS:END \*/",
                  lambda m: "/* TOKENS:BEGIN (gen.py inlines tokens.css here) */\n" + css() + "/* TOKENS:END */",
                  html, flags=re.S)
    open(pv, "w", encoding="utf-8").write(html)
print("wrote tokens.css, android/app/src/main/java/app/tidemark/design/DesignTokens.kt, preview.html")
